# In Python, keywords parameters are arguments passed to a functon by specifying the parameter name along with the value.


def introduce(name, age):
    print(f"My name is {name} and the age is {age}")
    
# introduce("Rahul", 20)  My name is Rahul and the age is 20
# introduce(name = "Rahul", age = 20)  Same => My name is Rahul and the age is 20

# BIG ADVANTAGE => With keyword parameters, order doesn't matter.

